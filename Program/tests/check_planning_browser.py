"""Headless UI exercise: case filters, budgets, missing inputs, exports and stale responses."""
import json
import sys
import threading
from pathlib import Path
from types import SimpleNamespace
from playwright.sync_api import sync_playwright, expect

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'src/demo'))
from server import make_server


def main():
    output=ROOT/'data/processed/planning_qa'
    output.mkdir(parents=True,exist_ok=True)
    server=make_server(SimpleNamespace(root=ROOT),0)
    thread=threading.Thread(target=server.serve_forever,daemon=True);thread.start()
    errors=[]
    try:
        with sync_playwright() as p:
            browser=p.chromium.launch(channel='msedge',headless=True)
            page=browser.new_page(viewport={'width':1440,'height':1000},device_scale_factor=1)
            page.on('pageerror',lambda error:errors.append(str(error)))
            page.goto(f'http://127.0.0.1:{server.server_port}/planning')
            expect(page.locator('#case-count')).to_contain_text('10 個案例')
            expect(page.locator('.case-entry')).to_have_count(10)
            page.locator('#case-search').fill('TOEM')
            expect(page.locator('.case-entry')).to_have_count(1)
            page.locator('.case-entry summary').click()
            expect(page.locator('.case-entry table')).to_contain_text('1,500,000 SEK')
            page.locator('#case-library').screenshot(path=str(output/'cases-desktop.png'))
            with page.expect_download() as event: page.get_by_role('link',name='來源 CSV',exact=True).click()
            event.value.save_as(str(output/'sources.csv'))
            assert (output/'sources.csv').read_bytes()==(ROOT.parent/'Dataset/Development Cost Cases/sources.csv').read_bytes()
            page.locator('#case-search').fill('')
            page.locator('#case-platform').select_option('Android')
            expect(page.locator('.case-entry')).to_have_count(1)
            expect(page.locator('.case-entry')).to_contain_text('Hang Line')
            page.locator('#case-search').fill('zz-no-result')
            expect(page.locator('#case-status')).to_contain_text('沒有符合')
            page.locator('#case-search').fill('');page.locator('#case-platform').select_option('')
            page.locator('#calculate-budget').click()
            expect(page.locator('#budget-results')).to_be_hidden()
            assert not page.locator('#budget-form').evaluate('(f)=>f.checkValidity()')
            page.locator('#load-example').click();page.locator('#calculate-budget').click()
            expect(page.locator('#budget-results')).to_be_visible()
            expect(page.locator('#budget-metrics')).to_contain_text('176,000')
            expect(page.locator('#budget-metrics')).to_contain_text('320,000')
            expect(page.locator('#requirements')).to_contain_text('14.4')
            expect(page.locator('#requirements')).to_contain_text('4,400')
            expect(page.locator('#delay-table')).to_contain_text('209,000')
            expect(page.locator('#budget-results svg')).to_have_count(4)
            expect(page.locator('#cost-chart svg')).to_contain_text('96,000')
            expect(page.locator('#resource-chart svg circle')).to_have_count(6)
            expect(page.locator('#resource-chart svg')).to_contain_text('320,000')
            expect(page.locator('#resource-chart')).to_contain_text('並非逐月現金流')
            expect(page.locator('#break-even-chart svg')).to_contain_text('4,400')
            expect(page.locator('#break-even-chart')).to_contain_text('不是預測銷量')
            with page.expect_download() as event:
                page.locator('#resource-chart').get_by_role('button',name='下載圖表 SVG').click()
            event.value.save_as(str(output/'planning-duration-resources.svg'))
            svg=(output/'planning-duration-resources.svg').read_text(encoding='utf-8')
            assert '<svg' in svg and '176,000' in svg and '320,000' in svg
            assert '來源：本次使用者輸入假設' in svg and '<script' not in svg
            page.locator('#budget-results').screenshot(path=str(output/'budget-desktop.png'))
            with page.expect_download() as event: page.locator('#budget-export').click()
            event.value.save_as(str(output/'budget-export.json'))
            exported=json.loads((output/'budget-export.json').read_text(encoding='utf-8'))
            assert exported['base']['cash_budget']==176000
            assert exported['request']['team'][1]['allocation']==0.5
            assert exported['data_kind']=='user_assumptions'
            page.locator('#net_unit_contribution').fill('0')
            expect(page.locator('#budget-results')).to_be_hidden()
            page.locator('#available_funds').fill('')
            page.locator('#calculate-budget').click()
            expect(page.locator('#requirements')).to_contain_text('沒有回本份數')
            expect(page.locator('#requirements')).to_contain_text('未提供資金')
            expect(page.locator('#break-even-chart svg')).to_have_count(0)
            expect(page.locator('#break-even-chart')).to_contain_text('不會把未知要求當作零')
            page.locator('#budget-currency').select_option('USD')
            expect(page.locator('#budget-status')).to_contain_text('未作匯率換算')
            expect(page.locator('#budget-results')).to_be_hidden()
            page.locator('#load-example').click()
            held=[]
            page.route('**/api/planning/budget',lambda route:held.append(route))
            page.locator('#calculate-budget').click()
            expect(page.locator('#calculate-budget')).to_be_disabled()
            page.locator('#budget-months').fill('15')
            assert len(held)==1
            held[0].continue_()
            expect(page.locator('#calculate-budget')).to_be_enabled()
            expect(page.locator('#budget-results')).to_be_hidden()
            page.unroute('**/api/planning/budget')
            page.locator('#calculate-budget').click()
            expect(page.locator('#budget-metrics')).to_contain_text('209,000')
            page.set_viewport_size({'width':390,'height':844})
            assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
            page.locator('#budget-results').screenshot(path=str(output/'budget-mobile.png'))
            page.locator('#case-search').fill('Fall of Lazarus')
            page.locator('.case-entry summary').click()
            expect(page.locator('.case-entry table')).to_contain_text('166,717')
            assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
            page.locator('#case-library').screenshot(path=str(output/'cases-mobile.png'))
            # Fees remain traceable, use explicit FX/eligibility, and renew in full terms.
            page.set_viewport_size({'width':1440,'height':1000})
            page.locator('#load-example').click()
            expect(page.locator('#fee-count')).to_contain_text('26 項')
            page.locator('#fee-search').fill('Unity')
            expect(page.locator('#fee-list tbody tr')).to_have_count(4)
            expect(page.locator('[data-add-fee="F004"]')).to_be_disabled()
            page.locator('[data-add-fee="F002"]').click()
            expect(page.locator('[data-add-fee="F003"]')).to_be_disabled()
            selected=page.locator('.fee-selection[data-fee-id="F002"]')
            selected.locator('[data-fee-field="quantity"]').fill('2')
            assert not page.locator('#budget-form').evaluate('(f)=>f.checkValidity()')
            selected.locator('[data-fee-field="fx_rate"]').fill('7.8')
            selected.locator('[data-fee-field="eligibility_confirmed"]').check()
            selected.locator('summary').click()
            expect(selected.locator('a').first).to_have_attribute('href','https://unity.com/products/pricing-updates')
            page.locator('#selected-fees').screenshot(path=str(output/'fees-selected-desktop.png'))
            page.locator('#calculate-budget').click()
            expect(page.locator('#budget-metrics')).to_contain_text('215,639.6')
            expect(page.locator('#delay-table')).to_contain_text('288,279.2')
            expect(page.locator('#fee-result-table')).to_contain_text('36,036')
            expect(page.locator('#requirements')).to_contain_text('10.44')
            with page.expect_download() as event:page.locator('#budget-export').click()
            event.value.save_as(str(output/'fee-budget-export.json'))
            exported=json.loads((output/'fee-budget-export.json').read_text(encoding='utf-8'))
            assert exported['fee_reference']['selections'][0]['fx_rate']==7.8
            assert exported['fee_reference']['selections'][0]['reference']['amount']=='2310'
            assert len(exported['fee_reference']['sources'])==2
            assert exported['delays'][1]['fee_lines'][0]['covered_months']==24
            selected.locator('[data-fee-field="fx_rate"]').fill('7.9')
            expect(page.locator('#budget-results')).to_be_hidden()
            page.locator('#budget-currency').select_option('USD')
            expect(selected.locator('[data-fee-field="fx_rate"]')).to_have_value('1')
            expect(selected.locator('[data-fee-field="eligibility_confirmed"]')).not_to_be_checked()
            selected.locator('[data-fee-field="eligibility_confirmed"]').check()
            page.locator('#calculate-budget').click()
            expect(page.locator('#budget-metrics')).to_contain_text('181,082')
            page.locator('[data-remove-fee="F002"]').click()
            expect(page.locator('#budget-results')).to_be_hidden()
            page.locator('#fee-search').fill('GitHub')
            page.locator('[data-add-fee="F019"]').click()
            monthly=page.locator('.fee-selection[data-fee-id="F019"]')
            monthly.locator('[data-fee-field="eligibility_confirmed"]').check()
            assert not page.locator('#budget-form').evaluate('(f)=>f.checkValidity()')
            monthly.locator('[data-fee-field="billing_assumption"]').select_option('monthly_flexible_user_assumption')
            monthly.locator('[data-fee-field="quantity"]').fill('3')
            page.locator('#calculate-budget').click()
            expect(page.locator('#budget-metrics')).to_contain_text('176,158.4')
            page.locator('#fee-search').fill('Unreal')
            expect(page.locator('[data-add-fee="F005"]')).to_be_disabled()
            page.locator('#fee-search').fill('no-matching-tool')
            expect(page.locator('#fee-status')).to_contain_text('沒有符合')
            page.locator('#fee-search').fill('')
            page.locator('#fee-currency').select_option('HKD')
            expect(page.locator('#fee-list tbody tr')).to_have_count(2)
            with page.expect_download() as event:page.get_by_role('link',name='費用來源 CSV',exact=True).click()
            event.value.save_as(str(output/'fee-sources.csv'))
            assert (output/'fee-sources.csv').read_bytes()==(ROOT.parent/'Dataset/Development Fee References/sources.csv').read_bytes()
            page.locator('#fee-library').screenshot(path=str(output/'fees-catalogue-desktop.png'))
            page.set_viewport_size({'width':390,'height':844})
            assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
            page.locator('#fee-library').screenshot(path=str(output/'fees-catalogue-mobile.png'))
            page.locator('#selected-fees').screenshot(path=str(output/'fees-selected-mobile.png'))
            assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
            page.locator('button[type=reset]').click()
            expect(page.locator('#budget-results')).to_be_hidden()
            expect(page.locator('.team-row')).to_have_count(1)
            expect(page.locator('.fee-selection')).to_have_count(0)
            # A missing fee catalogue does not break manual budgeting or case browsing.
            page.route('**/api/planning/fees',lambda route:route.fulfill(status=503,content_type='application/json',body='{"error":"Catalogue unavailable"}'))
            page.reload()
            expect(page.locator('#fee-status')).to_contain_text('手動預算')
            expect(page.locator('#case-count')).to_contain_text('10 個案例')
            page.locator('#load-example').click();page.locator('#calculate-budget').click()
            expect(page.locator('#budget-metrics')).to_contain_text('176,000')
            assert not errors,errors
            browser.close()
        print('Planning browser checks passed: cases, selected fees, terms/FX/eligibility, source exports, missing catalogue fallback, stale results and desktop/mobile layout.')
    finally:
        server.shutdown();server.server_close();thread.join()


if __name__=='__main__':main()
